#ifndef SFTP_DEMO_LOGGER_H
#define SFTP_DEMO_LOGGER_H

#include <string>

// ---------------------------------------------------------------------------
// 기능: 콘솔 + Client.log 파일 로거를 초기화한다.
// 역할: 프로세스 시작 시 1회 호출. 이후 LogXxx API 사용 가능.
// ---------------------------------------------------------------------------
void InitLogger();

// ---------------------------------------------------------------------------
// 기능: 정보성 운영 로그를 STEP과 함께 기록한다.
// 역할: 단계 시작, 설정값, 진행 상태를 콘솔과 Client.log에 남긴다.
// ---------------------------------------------------------------------------
void LogInfo(const char* step, const std::string& message);

// ---------------------------------------------------------------------------
// 기능: 경고 로그를 STEP과 함께 기록한다.
// 역할: 재시도 예정처럼 실패했지만 계속 진행하는 상황을 남긴다.
// ---------------------------------------------------------------------------
void LogWarn(const char* step, const std::string& message);

// ---------------------------------------------------------------------------
// 기능: 오류 로그를 STEP과 함께 기록한다.
// 역할: 연결/인증/다운로드 실패 사유를 운영자가 추적할 수 있게 남긴다.
// ---------------------------------------------------------------------------
void LogError(const char* step, const std::string& message);

// ---------------------------------------------------------------------------
// 기능: 성공 로그를 STEP과 함께 기록한다.
// 역할: 단계가 정상 끝났음을 콘솔과 Client.log에 남긴다.
// ---------------------------------------------------------------------------
void LogOk(const char* step, const std::string& message);

#endif

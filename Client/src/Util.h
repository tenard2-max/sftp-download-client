#ifndef SFTP_DEMO_UTIL_H
#define SFTP_DEMO_UTIL_H

#include <string>

// ---------------------------------------------------------------------------
// 기능: 문자열 앞뒤 공백/개행을 제거한다.
// 역할: config.ini 키·값과 fingerprint 비교 전에 불필요한 공백을 없앤다.
// ---------------------------------------------------------------------------
std::string Trim(const std::string& value);

// ---------------------------------------------------------------------------
// 기능: ASCII 문자를 소문자로 변환한다.
// 역할: 설정 키와 fingerprint를 대소문자 무시하고 비교한다.
// ---------------------------------------------------------------------------
std::string ToLowerAscii(const std::string& value);

// ---------------------------------------------------------------------------
// 기능: 파일 경로의 부모 폴더가 없으면 재귀 생성한다.
// 역할: LocalFile 저장 전 디렉터리 준비.
// ---------------------------------------------------------------------------
bool EnsureParentDirectory(const std::string& filePath);

// ---------------------------------------------------------------------------
// 기능: 현재 실행 중인 exe가 있는 디렉터리 경로를 반환한다.
// 역할: config.ini / Client.log 위치 결정.
// ---------------------------------------------------------------------------
std::string GetExecutableDirectory();

// ---------------------------------------------------------------------------
// 기능: 디렉터리와 파일명을 OS 경로로 합친다.
// 역할: exe 폴더 기준으로 config.ini, Client.log 경로를 만든다.
// ---------------------------------------------------------------------------
std::string JoinPath(const std::string& directory, const std::string& fileName);

#endif
